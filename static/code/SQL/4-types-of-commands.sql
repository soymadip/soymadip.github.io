-- We can devide sql commands into 5 categories:

- DDL (Data Definition Language): create, alter, drop, truncate, rename, drop
- DQL (Data Query Language): select
- DML (Data Manipulation Language): insert, update, delete
- DCL (Data Control Language): grant, revoke permissions to the users

- TCL (Transaction Control Language): [Advanced] start transaction, commit, rollback, savepoint, set transaction

